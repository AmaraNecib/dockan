        #[cfg(windows)]
        let owner = window.hwnd().map_err(|_| crate::backup_restore::FAILED)?.0 as isize;
        #[cfg(not(windows))]
        let owner = 0;
        let path = crate::backup_picker::choose(owner)?;
        restore_live(&app, &window, Some(pid))?;
