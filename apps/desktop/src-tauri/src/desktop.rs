    /// to prove the identity probe requires the real token echo.
    fn spawn_responder(f: impl Fn(&str) -> String + Send + 'static) -> (u16, std::thread::JoinHandle<()>, std::net::TcpListener) {
        let listener = std::net::TcpListener::bind("127.0.0.1:0").unwrap();
        let port = listener.local_addr().unwrap().port();
        let acceptor = listener.try_clone().unwrap();
        let handle = std::thread::spawn(move || {
            if let Ok((mut stream, _)) = acceptor.accept() {
                let mut buf = [0u8; 4096];
                let _ = stream.read(&mut buf);
                let request = String::from_utf8_lossy(&buf);
                let response = f(&request);
                let _ = stream.write_all(response.as_bytes());
            }
        });
        (port, handle, listener)
    }

