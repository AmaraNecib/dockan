//! Packaged-build bootstrap: spawn the Bun API sidecar, verify its identity,
//! then point the main window at the api's origin.
//!
//! Production topology (ticket 15): the web frontend calls the api with
//! relative `/api/*` URLs (same-origin contract it already uses through the
//! vite proxy in dev). In a packaged app there is no vite, so the api ITSELF
//! serves the built UI (`DOKAN_WEB_DIST`) and the window is navigated to
//! `http://127.0.0.1:<port>` — same origin, cookies and session work with no
//! CORS and no custom-protocol proxy. Data, logs, backups and the port record
//! live under the OS app-data dir in installed mode, or NEXT TO THE EXE
//! (`<exe-dir>/data`) in portable mode — a `portable.marker` file shipped
//! beside the exe flips the runtime to portable (issue 64): the marker sits
//! there and the folder is copyable anywhere and runs in place.
//!
//! Sidecar discovery (PR #51 findings 1 & TOCTOU): the shell spawns the
//! child, so the shell OWNS the port. It binds a listener on `127.0.0.1:0` —
//! the kernel assigns a truly free, now-reserved port, and the socket stays
//! bound until the child is spawned (no probe to race, no predictable port).
//! The exact port is handed to the child via `DOKAN_PORT` (authoritative: the
//! api binds it or exits loudly). Before navigating, the shell asks the child
//! for a one-time boot token (`DOKAN_BOOT_TOKEN`, generated by the shell and
//! echoed back by the api at `GET /health-token?token=…`) and compares the
//! echo byte-for-byte, AND cross-checks the port-record registry entry owned
//! by the child's pid. A stale, tampered, decoyed or race-hijacked record or
//! port can therefore never redirect the authenticated webview to an
//! unrelated localhost server.
//!
//! The same one-time token is injected into the webview's initial navigation
//! as a URL fragment (`/#setup_token=…`), and the api requires it for
//! `firstTimeSetup` in packaged builds. A local process that merely finds the
//! loopback port therefore cannot claim a fresh install as its own owner: it
//! never sees the token, which is never sent to the server and is stripped
//! from the visible URL once the web app reads it.
//!
//! Dev builds (`tauri dev`) never spawn the sidecar: the developer runs
//! `bun run dev:api` + `bun run dev:desktop` and the window loads the vite
//! devUrl unchanged. That devUrl is the app's own hostname (`dokan.localhost`,
//! #343), not `localhost`: a vault cookie written for the shared name is
//! handed to every other local service, because cookies ignore ports. The
//! tauri CLI cannot resolve that name — it is Rust, and the OS resolver does
//! not map `*.localhost` — so the dev script passes `--no-dev-server-wait`;
//! the CLI would otherwise panic while waiting for a dev server it can never
//! reach. The webview resolves it (WebView2 is Chromium), and the CLI reaches
//! the app after the cargo build, by which time vite is up.
//!
//! One universal build (ADR-0008): no secret is inlined into the sidecar.
//! The session-signing secret is generated by the api at first run and stored
//! in the portable database; this crate passes NO secrets to the child — only
//! the port, the data dir, the web dist and the one-time boot token are ever
//! in the child's environment.

