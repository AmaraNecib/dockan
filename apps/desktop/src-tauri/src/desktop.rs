    /// Release-blocking regression (the shipped bug): the packaged shell
    /// navigates the main window to `http://127.0.0.1:<port>`, which Tauri
    /// classifies as a REMOTE origin, and a capability reaches a remote webview
    /// only when its origin is listed under `remote.urls` (the local origin is
    /// the tauri:// asset protocol). Without that entry the vault gate's IPC
    /// bridge is absent, so setup/unlock dies with VAULT_UNEXPECTED and nothing
    /// ever reaches the sidecar. This drives the real Tauri URLPattern matcher
    /// over the shipped capability and the exact URL `setup_navigation_url`
    /// builds, so deleting the `remote` entry — or widening it to a wildcard
    /// host — fails here.
    #[test]
    fn default_capability_allows_the_loopback_origins_the_shell_loads() {
        use tauri::utils::acl::capability::CapabilityFile;
        use tauri::utils::acl::RemoteUrlPattern;
        use tauri::Url;

        let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
        let file = CapabilityFile::load(manifest.join("capabilities/default.json"))
            .expect("the default capability must parse");
        let capability = match file {
            CapabilityFile::Capability(capability) => capability,
            CapabilityFile::List(_) | CapabilityFile::NamedList { .. } => {
                panic!("default.json must hold a single capability")
            }
        };
        assert_eq!(capability.identifier, "default");

        let remote = capability.remote.expect(
            "the default capability must list the shell's loopback origins under remote.urls; \
             without it Tauri withholds the IPC bridge from the gate (VAULT_UNEXPECTED)",
        );
        let patterns: Vec<RemoteUrlPattern> = remote
            .urls
            .iter()
            .map(|url| url.parse().expect("each remote URL must be a valid URLPattern"))
            .collect();

        // the packaged origin is built by the very function the shell uses, so
        // a change to the navigation URL is covered too
        let packaged: Url = setup_navigation_url(4317, "deadbeef")
            .parse()
            .expect("the navigation URL must parse");
        assert!(
            patterns.iter().any(|pattern| pattern.test(&packaged)),
            "the capability must allow the packaged origin http://127.0.0.1:*"
        );

        // the vite dev server is the other origin the shell loads. It is the
        // app's own hostname, not `localhost` (#343): a cookie written for the
        // shared name reaches every other local service, and the vault broker
        // commands must not be granted to pages on it either.
        let dev: Url = "http://dokan.localhost:5173/".parse().unwrap();
        assert!(
            patterns.iter().any(|pattern| pattern.test(&dev)),
            "the capability must allow the vite dev origin http://dokan.localhost:*"
        );

        // scoped to loopback: a wildcard host would hand core permissions to
        // any remote page the webview is ever pointed at
        for non_loopback in [
            "http://10.0.0.7:4317/",
            "http://evil.example.com/",
            "http://127.0.0.1.evil.example.com/",
            "http://localhost.evil.example.com/",
            "http://dokan.localhost.evil.example.com/",
            // the shared name itself: the app moved off it, so a page served
            // by any other local service on `localhost` gets nothing
            "http://localhost:5173/",
        ] {
            let url: Url = non_loopback.parse().unwrap();
            assert!(
                !patterns.iter().any(|pattern| pattern.test(&url)),
                "{non_loopback} must not match a loopback-only capability"
            );
        }
    }

    /// A reachable IPC bridge is not enough: the capability must also resolve
    /// the shell's custom vault commands for the remote origin, otherwise the
    /// broker call is rejected by the ACL (and the web again reports
    /// VAULT_UNEXPECTED). This pins the resolved ACL the build actually embeds.
    #[test]
    fn default_capability_allows_the_vault_commands_from_the_remote_origin() {
        use std::collections::BTreeMap;
        use tauri::utils::acl::capability::Capability;
        use tauri::utils::acl::manifest::Manifest;
        use tauri::utils::acl::resolved::Resolved;
        use tauri::utils::acl::ExecutionContext;
        use tauri::utils::platform::Target;

        let manifest = Path::new(env!("CARGO_MANIFEST_DIR"));
        let read = |name: &str| {
            std::fs::read_to_string(manifest.join("gen/schemas").join(name))
                .unwrap_or_else(|err| panic!("{name} must be generated by the tauri build script: {err}"))
        };
        let acl: BTreeMap<String, Manifest> = serde_json::from_str(&read("acl-manifests.json")).unwrap();
        let capabilities: BTreeMap<String, Capability> = serde_json::from_str(&read("capabilities.json")).unwrap();
        let resolved = Resolved::resolve(&acl, capabilities, Target::Windows).unwrap();

        let origin: tauri::Url = "http://127.0.0.1:4317/".parse().unwrap();
        for command in [
            "vault_status",
            "vault_unlock",
            "vault_setup",
            "vault_unlock_recovery",
            "vault_reset_passphrase",
            "vault_setup_saved",
            "vault_setup_warning",
            "vault_logout",
        ] {
            let allowed = resolved.allowed_commands.get(command).is_some_and(|commands| {
                commands.iter().any(|resolved| {
                    matches!(&resolved.context, ExecutionContext::Remote { url } if url.test(&origin))
                })
            });
            assert!(allowed, "{command} must be allowed from the remote sidecar origin");
        }
    }

